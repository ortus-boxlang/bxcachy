#!/usr/bin/env python3
"""Turns the BxRig laptop (assets/brand/bxrig-laptop.png, a transparent render of bxrig-laptop.svg) into small colour pixel art for the terminal
and writes src/bxrig/BrandPixels.bx. One text row shows two pixel rows (upper and lower half blocks). Run when the logo changes:
    python3 tools/gen-brand-pixels.py       (needs Pillow; the output is committed, so building needs nothing extra)"""
import os
from PIL import Image, ImageEnhance, ImageFilter
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = Image.open(os.path.join(root, 'assets/brand/bxrig-laptop.png')).convert('RGBA')
src = src.crop(src.getbbox())
SIZES = {'large': 48, 'medium': 32, 'small': 20}
CHARS = "0123456789abcdefghijklmnopqrstuvwxyz"
out = []
for name, w in SIZES.items():
    h = round(w * src.size[1] / src.size[0]); h += h % 2
    im = src.resize((w, h), Image.LANCZOS)
    a = im.getchannel('A')
    rgb0 = ImageEnhance.Color(ImageEnhance.Contrast(im.convert('RGB')).enhance(1.25)).enhance(1.45).filter(ImageFilter.UnsharpMask(radius=0.6, percent=140, threshold=2))
    im = rgb0.convert('RGBA'); im.putalpha(a)
    rgb = Image.new('RGB', (w, h), (0, 0, 0)); rgb.paste(im.convert('RGB'))
    mask = [[im.getpixel((x, y))[3] >= 110 for x in range(w)] for y in range(h)]
    q = rgb.quantize(colors=36, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:36 * 3]
    used = {}
    rows = []
    for y in range(h):
        row = ''
        for x in range(w):
            if not mask[y][x]: row += '.'; continue
            i = q.getpixel((x, y))
            if i not in used: used[i] = CHARS[len(used)]
            row += used[i]
        rows.append(row)
    colors = ['#%02x%02x%02x' % tuple(pal[i * 3:i * 3 + 3]) for i in used]
    out.append((name, w, h, colors, rows))
lines = ['// GENERATED by tools/gen-brand-pixels.py from assets/brand/bxrig-laptop.png. Do not edit.',
         '// The BxRig laptop as colour pixel art: { w, h, palette: [ "#rrggbb" ], rows: [ strings ] }; "." is transparent and every other character indexes the palette',
         '// in the order it first appears. Two pixel rows make one text row (TuiKit.pixelArt draws them with half blocks).',
         'class BrandPixels {']
for name, w, h, colors, rows in out:
    pal = ', '.join('"%s"' % c for c in colors)
    lines.append('    function %s() {' % name)
    lines.append('        return { w: %d, h: %d, palette: [ %s ], rows: [' % (w, h, pal))
    lines.append(',\n'.join('            "%s"' % r for r in rows))
    lines.append('        ] };')
    lines.append('    }')
lines.append('}')
open(os.path.join(root, 'src/bxrig/BrandPixels.bx'), 'w').write('\n'.join(lines) + '\n')
print({n: (w, h, len(c)) for n, w, h, c, r in out})
