#!/usr/bin/env bash
# Embeds the BxRig agent skills (skills/*/SKILL.md) in src/bxrig/SkillData.bx (a generated class), like the templates.
#   gen-skills.sh           rewrite src/bxrig/SkillData.bx
#   gen-skills.sh --check   fail if the generated class is out of date (CI)
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/src/bxrig/SkillData.bx"
tmp="$(mktemp)"; trap 'rm -f "$tmp"' EXIT
{
  echo '// GENERATED by bootstrap/gen-skills.sh from skills/*/SKILL.md. Do not edit by hand.'
  echo 'class SkillData {'
  names=()
  for d in "$root"/skills/*/; do names+=("$(basename "$d")"); done
  echo '    function names() { return [ '"$(printf '"%s", ' "${names[@]}" | sed 's/, $//')"' ]; }'
  echo '    function text( name ) {'
  echo '        switch ( arguments.name ) {'
  for n in "${names[@]}"; do
    body="$(cat "$root/skills/$n/SKILL.md")"
    [[ "$body" != *\\* ]] || { echo "skills/$n/SKILL.md contains a backslash" >&2; exit 4; }
    lit="${body//\'/\'\'}"; lit="${lit//#/##}"
    echo "            case \"$n\":"
    printf "                return '%s' & chr( 10 );\n" "$lit"
  done
  echo '        }'
  echo '        return "";'
  echo '    }'
  echo '}'
} > "$tmp"
if [[ "${1:-}" == --check ]]; then
  cmp -s "$tmp" "$out" && echo "skills embed is current" || { echo "SkillData.bx is out of date: run bootstrap/gen-skills.sh" >&2; exit 1; }
else
  cp "$tmp" "$out"; echo "embedded ${#names[@]} skills into src/bxrig/SkillData.bx"
fi
