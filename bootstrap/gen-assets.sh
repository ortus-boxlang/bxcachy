#!/usr/bin/env bash
# Embeds the brand images (assets/) in src/bxrig/AssetData.bx as base64 (a generated class), like the catalog.
#   gen-assets.sh           rewrite src/bxrig/AssetData.bx
#   gen-assets.sh --check   fail if the generated class is out of date (CI)
# Rendering the images is separate: python3 assets/build.py && node assets/render.js
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/src/bxrig/AssetData.bx"
files=(icon.png logo.png wallpapers/box.jpg wallpapers/grid.jpg wallpapers/aurora.jpg wallpapers/minimal.png)
{
  echo '// GENERATED by bootstrap/gen-assets.sh from assets/. Do not edit by hand.'
  echo 'class AssetData {'
  echo '    function names() {'
  printf '        return [ '; sep=''; for f in "${files[@]}"; do printf '%s"%s"' "$sep" "$f"; sep=', '; done; echo ' ];'
  echo '    }'
  echo '    function base64( name ) {'
  echo '        switch ( arguments.name ) {'
  for f in "${files[@]}"; do
    echo "            case \"$f\":"
    echo "                return '$(base64 -w0 "$root/assets/$f")';"
  done
  echo '        }'
  echo '        return "";'
  echo '    }'
  echo '}'
} > "$out.new"
if [[ "${1:-}" == --check ]]; then
  cmp -s "$out.new" "$out" && { rm -f "$out.new"; echo 'asset embed is current'; } || { rm -f "$out.new"; echo 'src/bxrig/AssetData.bx is out of date: run bootstrap/gen-assets.sh' >&2; exit 1; }
else
  mv "$out.new" "$out"; echo "embedded ${#files[@]} images into src/bxrig/AssetData.bx ($(wc -c < "$out") bytes)"
fi
