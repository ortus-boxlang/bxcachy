#!/usr/bin/env bash
# Embeds the starter config templates (templates/) in src/bxrig/TemplateData.bx (a generated class), like the catalog.
#   gen-templates.sh           rewrite src/bxrig/TemplateData.bx
#   gen-templates.sh --check   fail if the generated class is out of date (CI)
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/src/bxrig/TemplateData.bx"
files=(hyprland.lua starship.toml shell.zsh shell.bash shell.fish nvim/lua/config/bxrig.lua nvim/lua/plugins/bxrig.lua nvim/lua/plugins/boxlang.lua nvim/lua/plugins/bxrig-themes.lua nvim/lua/plugins/bxrig-theme-reload.lua nvim/plugin/after/bxrig-transparency.lua)
{
  echo '// GENERATED by bootstrap/gen-templates.sh from templates/. Do not edit by hand.'
  echo 'class TemplateData {'
  echo '    function text( name ) {'
  echo '        switch ( arguments.name ) {'
  for f in "${files[@]}"; do
    body="$(cat "$root/templates/$f")"
    # MatchBox string literals do not keep backslashes: each one becomes a marker that text() turns back into chr( 92 ).
    bs=0; [[ "$body" != *\\* ]] || bs=1
    body="${body//\\/@@BS@@}"
    lit="${body//\'/\'\'}"; lit="${lit//#/##}"
    echo "            case \"$f\":"
    if [[ $bs == 1 ]]; then printf "                return replace( '%s' & chr( 10 ), '@@BS@@', chr( 92 ), 'all' );\n" "$lit"
    else printf "                return '%s' & chr( 10 );\n" "$lit"; fi
  done
  # the nvm pin comes from box.json (the one place that names tool versions)
  nvm="$(jq -c .toolchain.nvm "$root/box.json")"
  [[ "$nvm" != *\\* ]] || { echo "box.json toolchain.nvm contains a backslash" >&2; exit 4; }
  lit="${nvm//\'/\'\'}"; lit="${lit//#/##}"
  echo '            case "nvm.json":'
  printf "                return '%s';\n" "$lit"
  echo '        }'
  echo '        return "";'
  echo '    }'
  echo '}'
} > "$out.new"
if [[ "${1:-}" == --check ]]; then
  cmp -s "$out.new" "$out" && { rm -f "$out.new"; echo 'template embed is current'; } || { rm -f "$out.new"; echo 'src/bxrig/TemplateData.bx is out of date: run bootstrap/gen-templates.sh' >&2; exit 1; }
else
  mv "$out.new" "$out"; echo "embedded ${#files[@]} templates into src/bxrig/TemplateData.bx"
fi
