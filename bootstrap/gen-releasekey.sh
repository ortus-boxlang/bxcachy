#!/usr/bin/env bash
# Embeds keys/release.pub (the release signing public key) in src/bxrig/ReleaseKey.bx, like the catalog and templates.
#   gen-releasekey.sh           rewrite src/bxrig/ReleaseKey.bx
#   gen-releasekey.sh --check   fail if it is out of date (CI)
# With no keys/release.pub the class returns an empty key and the binary does not verify signatures (a development build).
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/src/bxrig/ReleaseKey.bx"
pem=""; [[ ! -f "$root/keys/release.pub" ]] || pem="$(cat "$root/keys/release.pub")"
[[ "$pem" != *\\* && "$pem" != *\'* && "$pem" != *#* ]] || { echo "keys/release.pub has characters that cannot be embedded" >&2; exit 4; }
body="// GENERATED by bootstrap/gen-releasekey.sh from keys/release.pub. Do not edit by hand.
// The public key that release manifests are verified with (Ed25519). Empty: this build does not verify signatures.
class ReleaseKey {
    function pem() { return '${pem}'; }
}"
if [[ "${1:-}" == --check ]]; then
  [[ "$(cat "$out" 2>/dev/null)" == "$body" ]] && echo "release key embed is current" || { echo "ReleaseKey.bx is out of date: run bootstrap/gen-releasekey.sh" >&2; exit 1; }
else
  printf '%s\n' "$body" > "$out"; echo "embedded the release key into src/bxrig/ReleaseKey.bx (${#pem} bytes)"
fi
