#!/usr/bin/env python3
"""Generates src/art.rs: the BoxLang icon and the BxCachy wordmark as half-block pixel art.
Usage: python3 wizard/gen-art.py   (needs Pillow and node with playwright, as assets/render.js does)"""
import base64, os, subprocess, sys, tempfile, textwrap
from PIL import Image, ImageDraw, ImageFont
here = os.path.dirname(os.path.abspath(__file__))
icon_svg = os.path.join(here, '..', 'assets', 'brand', 'boxlang-icon-full.svg')

def raster_icon(px):
    """Rasterise the official icon to a px x px alpha mask with Chromium."""
    tmp = tempfile.mkdtemp()
    html = os.path.join(tmp, 'i.html'); png = os.path.join(tmp, 'i.png')
    open(html, 'w').write(f'<body style="margin:0;background:transparent"><img src="file://{os.path.abspath(icon_svg)}" width="{px*4}" height="{px*4}"></body>')
    js = os.path.join(tmp, 'r.js')
    open(js, 'w').write(f"const {{chromium}}=require('playwright');(async()=>{{const b=await chromium.launch();const p=await b.newPage({{viewport:{{width:{px*4},height:{px*4}}}}});await p.goto('file://{html}');await p.screenshot({{path:'{png}',omitBackground:true}});await b.close();}})();")
    subprocess.run(['node', js], check=True, env={**os.environ, 'NODE_PATH': subprocess.check_output(['npm', 'root', '-g']).decode().strip()})
    return Image.open(png).convert('RGBA').resize((px, px), Image.LANCZOS)

def to_halfblocks(mask):
    """mask: PIL 'L' image; rows of ' ', '▀', '▄', '█' (two pixel rows per text row)."""
    w, h = mask.size
    if h % 2: h += 1
    px = lambda x, y: y < mask.size[1] and mask.getpixel((x, y)) > 110
    rows = []
    for y in range(0, h, 2):
        row = ''
        for x in range(w):
            top, bot = px(x, y), px(x, y + 1)
            row += '█' if top and bot else '▀' if top else '▄' if bot else ' '
        rows.append(row.rstrip())
    while rows and not rows[-1].strip(): rows.pop()
    return rows

icon = raster_icon(30)
icon_rows = to_halfblocks(icon.split()[3])

def wordmark(text, size):
    font = ImageFont.truetype('/usr/share/fonts/truetype/jetbrains-mono/JetBrainsMono-Bold.ttf', size)
    box = font.getbbox(text)
    img = Image.new('L', (box[2] + 2, box[3] + 2), 0)
    ImageDraw.Draw(img).text((0, 0), text, font=font, fill=255)
    bb = img.getbbox(); img = img.crop(bb)
    return to_halfblocks(img)

mark_rows = wordmark('BxCachy', 18)

def rust_const(name, rows):
    body = ',\n'.join('    "%s"' % r for r in rows)
    return f'pub const {name}: &[&str] = &[\n{body},\n];\n'

open(os.path.join(here, 'src', 'art.rs'), 'w').write(
    '// GENERATED by wizard/gen-art.py from the official BoxLang icon and a wordmark. Do not edit by hand.\n'
    '// Half-block pixel art: each character is two pixel rows (\' \', \'▀\', \'▄\', \'█\').\n\n'
    + rust_const('ICON', icon_rows) + '\n' + rust_const('WORDMARK', mark_rows))
print('icon', len(icon_rows), 'rows x', max(len(r) for r in icon_rows), '; wordmark', len(mark_rows), 'rows x', max(len(r) for r in mark_rows))
